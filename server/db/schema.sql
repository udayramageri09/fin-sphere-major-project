-- FinSphere PostgreSQL schema. Idempotent: safe to run on every startup.
-- All financial domains use PostgreSQL. Legacy JSON imports require an explicit
-- migration policy; production never imports them implicitly.

CREATE TABLE IF NOT EXISTS users (
  -- BIGINT (not UUID) on purpose: existing JSON-backed transactions/goals/liabilities are
  -- owned by the numeric user id issued before this migration, and the JWT carries it.
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Stored already normalized (trimmed, lower-case); the CHECK makes the database refuse
  -- anything else so the UNIQUE constraint really means "one account per address".
  email         TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT users_email_unique UNIQUE (email),
  CONSTRAINT users_email_normalized CHECK (email = lower(btrim(email)) AND length(email) BETWEEN 3 AND 254),
  -- A bcrypt hash only; a plaintext password cannot be inserted by mistake.
  CONSTRAINT users_password_is_bcrypt CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$.{53}$')
);

-- Password recovery: only a digest is persisted; one active link per user.
ALTER TABLE users ADD COLUMN IF NOT EXISTS reset_token_hash TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS reset_token_expires_at TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS reset_requested_at TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS session_version INTEGER NOT NULL DEFAULT 0;
CREATE UNIQUE INDEX IF NOT EXISTS users_reset_token_hash_idx ON users(reset_token_hash) WHERE reset_token_hash IS NOT NULL;

-- Records one-off data migrations (e.g. the import of server_users.json) so they run once.
CREATE TABLE IF NOT EXISTS schema_migrations (
  name       TEXT PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Transactions. Replaces server_db.json (one-time import at startup, see db/index.js).
CREATE TABLE IF NOT EXISTS transactions (
  -- Internal insertion order and primary key. The API lists newest first, and a bulk import
  -- keeps its own file order, so ordering is by this column rather than by date.
  seq      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  -- The public id, stored as text: new rows are UUIDs, historical rows are numeric-looking
  -- (e.g. 1789492582865) and are kept exactly as they were. It is deliberately NOT unique:
  -- legacy imports produced repeated ids, and deleting by id removes exactly one owned row.
  id       TEXT NOT NULL CHECK (length(id) BETWEEN 1 AND 64),
  user_id  BIGINT NOT NULL REFERENCES users(id),
  title    TEXT NOT NULL CHECK (title = btrim(title) AND length(title) BETWEEN 1 AND 120),
  -- Exact money: NUMERIC, never floating point. Signed (income > 0, expense < 0).
  amount   NUMERIC(14, 2) NOT NULL,
  type     TEXT NOT NULL CHECK (type IN ('income', 'expense')),
  date     DATE NOT NULL,
  category TEXT NOT NULL DEFAULT 'General' CHECK (length(btrim(category)) > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- The sign always follows the type, and zero is not a transaction.
  CONSTRAINT transactions_sign_matches_type CHECK (
    (type = 'income' AND amount > 0) OR (type = 'expense' AND amount < 0)
  )
);

-- Owner lookups (list, delete by id) and newest-first listing.
CREATE INDEX IF NOT EXISTS transactions_user_seq_idx ON transactions (user_id, seq DESC);
CREATE INDEX IF NOT EXISTS transactions_user_id_idx ON transactions (user_id, id);

-- Analytical classification (Issue #59). `type` (income | expense) keeps meaning direction and sign; `classification`
-- says what the money WAS, for analysis. Every existing row only ever proved its direction, so existing rows become
-- 'unknown' (the column default fills them when it is added): no semantic meaning is fabricated for old data.
-- Idempotent: safe on a fresh database and on every start of an existing one.
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS classification TEXT NOT NULL DEFAULT 'unknown';
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'transactions_classification_valid' AND conrelid = 'transactions'::regclass) THEN
    ALTER TABLE transactions ADD CONSTRAINT transactions_classification_valid
      CHECK (classification IN ('income', 'expense', 'refund', 'transfer', 'unknown'));
  END IF;
  -- Direction is never inferred from the classification: an income-direction row can be income / refund / transfer /
  -- unknown, an expense-direction row can be expense / transfer / unknown. Nothing else is a coherent combination.
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'transactions_classification_matches_type' AND conrelid = 'transactions'::regclass) THEN
    ALTER TABLE transactions ADD CONSTRAINT transactions_classification_matches_type CHECK (
      (type = 'income'  AND classification IN ('income', 'refund', 'transfer', 'unknown')) OR
      (type = 'expense' AND classification IN ('expense', 'transfer', 'unknown'))
    );
  END IF;
END
$$;

-- Savings goals. Replaces server_goals.json (one-time import at startup, see db/index.js).
CREATE TABLE IF NOT EXISTS goals (
  -- Insertion order: the API lists newest first (new rows used to be unshifted onto the front).
  seq            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id             TEXT NOT NULL CHECK (length(id) BETWEEN 1 AND 64),
  user_id        BIGINT NOT NULL REFERENCES users(id),
  title          TEXT NOT NULL CHECK (title = btrim(title) AND length(title) BETWEEN 1 AND 120),
  -- Exact money. Unconstrained NUMERIC on purpose: goals have no upper cap (unlike transactions), and any
  -- finite JS number (up to ~1.8e308) must be storable. The upper bound below only excludes NaN / Infinity
  -- (PostgreSQL orders NaN above every number and Infinity above every finite one).
  target_amount  NUMERIC NOT NULL CHECK (target_amount > 0 AND target_amount < 1e310),
  current_amount NUMERIC NOT NULL CHECK (current_amount >= 0 AND current_amount <= target_amount),
  target_date    DATE NOT NULL,
  created_at     TIMESTAMPTZ NOT NULL,
  CONSTRAINT goals_user_id_id_unique UNIQUE (user_id, id)
);

CREATE INDEX IF NOT EXISTS goals_user_seq_idx ON goals (user_id, seq DESC);

-- Liabilities. Replaces server_liabilities.json (one-time import at startup, see db/index.js).
CREATE TABLE IF NOT EXISTS liabilities (
  -- Insertion order: the API lists newest first (new rows used to be unshifted onto the front).
  seq                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id                 TEXT NOT NULL CHECK (length(id) BETWEEN 1 AND 64),
  user_id            BIGINT NOT NULL REFERENCES users(id),
  name               TEXT NOT NULL CHECK (name = btrim(name) AND length(name) BETWEEN 1 AND 120),
  type               TEXT NOT NULL CHECK (type IN ('home_loan', 'personal_loan', 'vehicle_loan', 'education_loan', 'credit_card', 'other')),
  -- Exact money / rates. Unconstrained NUMERIC on purpose: liabilities have no upper cap (unlike transactions),
  -- so any finite JS number (up to ~1.8e308) must be storable. The "< 1e310" bounds only exclude NaN and
  -- Infinity (PostgreSQL orders NaN above every number and Infinity above every finite one).
  -- 0 means fully repaid (see liability_repayments); a new liability is still validated as > 0 by the API.
  outstanding_amount NUMERIC NOT NULL,
  interest_rate      NUMERIC NOT NULL CHECK (interest_rate >= 0 AND interest_rate <= 100),
  monthly_payment    NUMERIC NOT NULL CHECK (monthly_payment >= 0 AND monthly_payment < 1e310),
  created_at         TIMESTAMPTZ NOT NULL,
  CONSTRAINT liabilities_user_id_id_unique UNIQUE (user_id, id)
);

-- A repaid liability keeps its row with outstanding_amount = 0, so the balance rule is >= 0. Databases created
-- before repayments existed carry the old unnamed "> 0" check; replace it once (idempotent on every start).
ALTER TABLE liabilities DROP CONSTRAINT IF EXISTS liabilities_outstanding_amount_check;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'liabilities_outstanding_nonnegative' AND conrelid = 'liabilities'::regclass) THEN
    ALTER TABLE liabilities ADD CONSTRAINT liabilities_outstanding_nonnegative CHECK (outstanding_amount >= 0 AND outstanding_amount < 1e310);
  END IF;
END
$$;

CREATE INDEX IF NOT EXISTS liabilities_user_seq_idx ON liabilities (user_id, seq DESC);

-- Emergency fund: at most one record per user (the user_id primary key enforces it).
CREATE TABLE IF NOT EXISTS emergency_funds (
  user_id        BIGINT PRIMARY KEY REFERENCES users(id),
  -- Exact money, no storage-convenience cap (a transaction-style limit does not apply). The "< 1e310" bounds
  -- only exclude NaN / Infinity (PostgreSQL orders NaN above every number and Infinity above every finite one).
  -- A current amount of 0 is a real, configured value; "not configured" is the absence of the row.
  current_amount NUMERIC NOT NULL CHECK (current_amount >= 0 AND current_amount < 1e310),
  -- Optional goal for the fund. It may be smaller than current_amount (a user can exceed their target).
  target_amount  NUMERIC CHECK (target_amount IS NULL OR (target_amount > 0 AND target_amount < 1e310)),
  created_at     TIMESTAMPTZ NOT NULL,
  updated_at     TIMESTAMPTZ NOT NULL
);

-- Contributions toward a savings goal. goals.current_amount is the running balance (it starts at whatever the
-- user entered when creating the goal; no history is invented for it) and every row here is one later, real
-- deposit. A contribution and the balance update are written in one transaction (see addGoalContribution).
CREATE TABLE IF NOT EXISTS goal_contributions (
  -- Insertion order: history is listed newest first, deterministically.
  seq        BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id         TEXT NOT NULL UNIQUE CHECK (length(id) BETWEEN 1 AND 64),
  user_id    BIGINT NOT NULL,
  goal_id    TEXT NOT NULL,
  -- Exact money; positive only for now. No transaction-style cap (the "< 1e310" bound only excludes NaN / Infinity).
  amount     NUMERIC NOT NULL CHECK (amount > 0 AND amount < 1e310),
  created_at TIMESTAMPTZ NOT NULL,
  -- The composite key ties a contribution to a goal owned by the same user; deleting a goal removes its history.
  CONSTRAINT goal_contributions_goal_fk FOREIGN KEY (user_id, goal_id) REFERENCES goals (user_id, id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS goal_contributions_goal_idx ON goal_contributions (user_id, goal_id, seq DESC);

-- Repayments toward a liability. liabilities.outstanding_amount is the running balance (no history is invented for
-- balances that existed before) and every row here is one later, real repayment. A repayment and the balance
-- reduction are written in one transaction (see repayLiability).
CREATE TABLE IF NOT EXISTS liability_repayments (
  -- Insertion order: history is listed newest first, deterministically.
  seq          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id           TEXT NOT NULL UNIQUE CHECK (length(id) BETWEEN 1 AND 64),
  user_id      BIGINT NOT NULL,
  liability_id TEXT NOT NULL,
  -- Exact money, positive only; no cap (the "< 1e310" bound only excludes NaN / Infinity).
  amount       NUMERIC NOT NULL CHECK (amount > 0 AND amount < 1e310),
  created_at   TIMESTAMPTZ NOT NULL,
  -- Ties a repayment to a liability owned by the same user; deleting the liability removes its history.
  CONSTRAINT liability_repayments_liability_fk FOREIGN KEY (user_id, liability_id) REFERENCES liabilities (user_id, id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS liability_repayments_liability_idx ON liability_repayments (user_id, liability_id, seq DESC);

-- Monthly category budgets: at most one per user + calendar month + category.
CREATE TABLE IF NOT EXISTS budgets (
  id         TEXT PRIMARY KEY CHECK (length(id) BETWEEN 1 AND 64),
  user_id    BIGINT NOT NULL REFERENCES users(id),
  -- The first day of the budget's calendar month (the API speaks 'YYYY-MM'). Never derived from a time zone.
  month      DATE NOT NULL CHECK (extract(day FROM month) = 1),
  -- What the user typed (trimmed); shown in the UI.
  label      TEXT NOT NULL CHECK (label = btrim(label) AND length(label) BETWEEN 1 AND 60),
  -- The canonical category key, always lower(btrim(label)) (a generated column, so it cannot disagree with the
  -- label). "Food", "food" and " FOOD " are one budget. A transaction belongs to a budget when
  -- lower(btrim(transaction.category)) = budgets.category; no other mapping exists (Dining is not Food).
  category   TEXT GENERATED ALWAYS AS (lower(btrim(label))) STORED,
  -- Exact money, positive; no transaction-style cap (the "< 1e310" bound only excludes NaN / Infinity).
  amount     NUMERIC NOT NULL CHECK (amount > 0 AND amount < 1e310),
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  -- The database, not application code, guarantees one budget per user / month / category (also under races).
  CONSTRAINT budgets_user_month_category_unique UNIQUE (user_id, month, category)
);

CREATE INDEX IF NOT EXISTS budgets_user_month_idx ON budgets (user_id, month);

-- Confirmed assistant actions (Issue #73). The assistant never writes financial data from a chat message: it stores a
-- PROPOSAL here (what it would do, in its already-validated form), the user confirms it, and only then does the server
-- run the same write code the manual forms use. A proposal belongs to one user and executes at most once.
--   draft      a clarification is in progress (a field is still missing or ambiguous); nothing can execute
--   pending    complete and previewed; waiting for the user's explicit confirmation
--   executing  claimed by exactly one confirmation (the atomic pending -> executing UPDATE decides the winner)
--   executed   written; `result` holds what was stored so a repeated confirmation can return it without writing again
--   failed     the write was refused (e.g. the goal target would be exceeded); nothing was stored
--   cancelled  the user said no, edited it, or moved on
--   expired    the confirmation window passed
CREATE TABLE IF NOT EXISTS assistant_action_proposals (
  id         TEXT PRIMARY KEY CHECK (length(id) BETWEEN 1 AND 64),
  user_id    BIGINT NOT NULL REFERENCES users(id),
  kind       TEXT NOT NULL,
  payload    JSONB NOT NULL,
  summary    TEXT NOT NULL,
  display    JSONB NOT NULL,
  status     TEXT NOT NULL CHECK (status IN ('draft', 'pending', 'executing', 'executed', 'failed', 'cancelled', 'expired')),
  result     JSONB,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);

-- The allowed action kinds. CREATE TABLE IF NOT EXISTS never changes a table that already exists, so the rule lives in
-- a named constraint that is (re)created whenever the stored definition does not yet list every current kind. A database
-- made by Issue #73 has the old unnamed check (assistant_action_proposals_kind_check, two kinds): it is dropped here.
-- Safe to run on every startup: once the definition is current, nothing happens.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'assistant_action_proposals_kind_valid' AND conrelid = 'assistant_action_proposals'::regclass
      AND pg_get_constraintdef(oid) LIKE '%record_liability_repayment%' AND pg_get_constraintdef(oid) LIKE '%set_budget%'
      AND pg_get_constraintdef(oid) LIKE '%create_liability%'
  ) THEN
    ALTER TABLE assistant_action_proposals DROP CONSTRAINT IF EXISTS assistant_action_proposals_kind_check;
    ALTER TABLE assistant_action_proposals DROP CONSTRAINT IF EXISTS assistant_action_proposals_kind_valid;
    ALTER TABLE assistant_action_proposals ADD CONSTRAINT assistant_action_proposals_kind_valid
      CHECK (kind IN ('create_transaction', 'contribute_to_goal', 'record_liability_repayment', 'set_budget', 'create_liability'));
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS assistant_action_proposals_user_status_idx ON assistant_action_proposals (user_id, status);
-- At most one open (draft or pending) proposal per user: a new request replaces the old one instead of piling up.
CREATE UNIQUE INDEX IF NOT EXISTS assistant_action_proposals_one_open_idx
  ON assistant_action_proposals (user_id) WHERE status IN ('draft', 'pending');

